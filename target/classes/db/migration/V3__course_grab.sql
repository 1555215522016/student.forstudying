-- 选修课程表
-- capacity = 总名额，selected_count 由延迟落库维护（Redis 是热口径，此表是持久口径/对账基准）
CREATE TABLE IF NOT EXISTS t_course (
    id             BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    code           VARCHAR(32)  NOT NULL COMMENT '课程编号（如 14001）',
    name           VARCHAR(64)  NOT NULL COMMENT '课程名称',
    teacher        VARCHAR(64)  NOT NULL COMMENT '授课教师',
    capacity       INT          NOT NULL DEFAULT 100 COMMENT '课程容量（总名额）',
    selected_count INT          NOT NULL DEFAULT 0 COMMENT '已选人数（延迟落库维护，对账用）',
    class_time     VARCHAR(64)  DEFAULT NULL COMMENT '上课时间（如 周一1-2节）',
    status         TINYINT      NOT NULL DEFAULT 1 COMMENT '课程状态：0未开始 1抢课中 2已满 3已结束',
    deleted        TINYINT      NOT NULL DEFAULT 0 COMMENT '逻辑删除：0正常 1已删除',
    created_at     DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at     DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_code (code),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='选修课程表';

-- 选课记录表
-- status = 状态流转核心字段（0待处理 1已选 2已退 3选课失败）
-- UNIQUE (user_id, course_id) 同时兜接口幂等 + MQ消费幂等：重复插入一律拒绝
CREATE TABLE IF NOT EXISTS t_course_selection (
    id         BIGINT   NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    user_id    BIGINT   NOT NULL COMMENT '学生ID（关联 t_user.id）',
    course_id  BIGINT   NOT NULL COMMENT '课程ID（关联 t_course.id）',
    status     TINYINT  NOT NULL DEFAULT 1 COMMENT '选课状态：0待处理 1已选 2已退 3选课失败',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_course (user_id, course_id),
    KEY idx_course_id (course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='选课记录表';

